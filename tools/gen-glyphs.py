def render_glyph(strokes):
    img = Image.new('RGBA', (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    for s in strokes:
        kind = s[0]
        if kind == 'line':
            d.line(s[1:], fill=INK, width=WIDTH)
        elif kind == 'dot':
            d.ellipse((s[1] - s[3], s[2] - s[3], s[1] + s[3], s[2] + s[3]), fill=INK)
        elif kind == 'arc':
            d.arc((s[1] - s[3], s[2] - s[3], s[1] + s[3], s[2] + s[3]), s[4], s[5], fill=INK, width=WIDTH)
        elif kind == 'circle':
            d.ellipse((s[1] - s[3], s[2] - s[3], s[1] + s[3], s[2] + s[3]), outline=INK, width=WIDTH)
        elif kind == 'ellipse':
            d.ellipse(s[1:], outline=INK, width=WIDTH)
        elif kind == 'rect':
            d.rectangle(s[1:], outline=INK, width=WIDTH)
        else:
            raise ValueError('未知笔画原语：%r' % kind)
    return img


def build(out_root):
    out_root = Path(out_root)
    written = []
    for gid, (ctype, strokes) in sorted(GLYPHS.items()):
        img = render_glyph(strokes)
        dest_dir = out_root / ctype
        dest_dir.mkdir(parents=True, exist_ok=True)
        dest = dest_dir / (gid + '.png')
        img.save(dest)
        written.append(dest)
    return written


def selftest():
    failures = []
    with tempfile.TemporaryDirectory() as td:
        tdr = Path(td)
        written = build(tdr)
        if len(written) != len(GLYPHS):
            failures.append('应渲染 %d 个字形，实 %d' % (len(GLYPHS), len(written)))
        # 每个字形的 png 必须非空、尺寸正确、且透明底
        for dest in written:
            im = Image.open(dest)
            if im.size != (SIZE, SIZE):
                failures.append('%s 尺寸错：%s' % (dest.name, im.size))
            if im.mode != 'RGBA':
                failures.append('%s 非透明底' % dest.name)
            # 透明底：四角必须全透明
            corner = im.getpixel((0, 0))
            if corner[3] != 0:
                failures.append('%s 四角不透明（应为透明底）' % dest.name)
        # 复算：再跑一次，字节必须一致
        tdr2 = Path(tempfile.mkdtemp())
        build(tdr2)
        for dest in written:
            again = tdr2 / dest.relative_to(tdr)
            if dest.read_bytes() != again.read_bytes():
                failures.append('%s 两次渲染不一致' % dest.name)
    if failures:
        print('gen-glyphs.py selftest FAILED:')
        for f in failures:
            print('  - ' + f)
        return 1
    print('gen-glyphs.py selftest ok（%d 个字形）' % len(GLYPHS))
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description='生成甲骨文字形 PNG')
    ap.add_argument('--out', default=str(CHARS), help='输出根目录（默认 characters/）')
    ap.add_argument('--selftest', action='store_true')
    args = ap.parse_args(argv)
    if args.selftest:
        return selftest()
    written = build(Path(args.out))
    print('rendered %d glyphs → %s' % (len(written), Path(args.out)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
